-- 【グラム換算の基準（重要）】
-- `grams_per_unit` は **可食部（正味）重量** を表す。`food_items` の成分値は
-- 「日本食品標準成分表（八訂）増補2023年」の可食部100gあたりの値であり、
-- `UnitConversionService.toGrams` の結果はそのまま100gあたり栄養価に乗じられる
-- （design.md #NutritionVerificationService）。したがって皮・殻・軸などの廃棄部を
-- 含む「購入時重量」ではなく、廃棄部を除いた正味重量を投入している。
-- 出典(B)は正味重量をそのまま与える。出典(A)(C)の「見当量（廃棄部分含む）」から
-- 採否を判断する際は、成分表の廃棄率（REFUSE）を適用した値と(B)が整合することを
-- 確認した（例: 卵 見当量60g × (1 − 廃棄率14%) = 51.6g ≒ (B)の50g、
-- キャベツ (B)1玉1000g ÷ (1 − 廃棄率15%) = 1176g ≒ (C)の1個1200g）。
--
-- 【投入方針】
-- 1. 汎用エントリ（`food_id IS NULL`）は、食材によらず容量が定義されている計量単位
--    （大さじ・小さじ・カップ・ml・cc）についてのみ投入する。基準は水（および酢・酒などの
--    一般的な液体）で、計量器の容量定義と水の密度1g/mLから大さじ15g・小さじ5g・
--    カップ200g・ml 1g・cc 1gとなる。
-- 2. `個`・`本`・`枚`・`束`・`玉`・`丁`・`パック`・`缶` といった計数単位には汎用エントリを
--    **投入しない**。これらの1単位あたり重量は食材ごとに固有（卵1個50g、たまねぎ1個200g）
--    であり、全食材に妥当な既定値が存在しないためである。該当する食材固有エントリが
--    無い場合はRequirement 5.4の `unit_not_found` として生成を失敗させる方が、
--    根拠のない既定値で誤った栄養価を算出するより安全である。
-- 3. 調味料・粉類・油脂類の `大さじ`・`小さじ`・`カップ` は水基準の汎用エントリとは
--    密度が大きく異なる（しょうゆ大さじ1=18g、砂糖大さじ1=9g、油大さじ1=12g）ため、
--    食材固有エントリで上書きする。これがRequirement 5.2「食材固有エントリの優先」の
--    実データ上の主要な適用例である。
-- 4. 出典が一般名で示す食品（「しょうゆ」「みそ」「油」「バター」「小麦粉」など）は、
--    その一般名が素直に指す `food_items` の行にのみ適用する。出典が想定していたと
--    断定できない変種（減塩しょうゆ・低脂肪ヨーグルト・グラニュー糖・みりん風調味料など）
--    には適用しない。
-- 5. 実在する出典値を確認できなかった `(food_id, unit_code)` の組み合わせは投入しない。
--    推定値で埋めることはしない。
--
-- 【重要: 未投入時の挙動は単位の種類によって非対称である】
-- 「投入しなければ `unit_not_found` になるから安全」というのは **計数単位に限った話** であり、
-- 計量単位には当てはまらない。両者を混同しないこと。
--
--  (i) 計数単位（個・本・枚・玉・丁・束・パック・缶）— 汎用エントリを投入していないため、
--      食材固有エントリが無ければ食材固有・汎用のいずれも見つからず、
--      Requirement 5.4の `unit_not_found` となり生成全体が失敗する。
--      これは「大きく外れた値を黙って使う」ことを防ぐ、意図した安全側の失敗である。
--
--  (ii) 計量単位（大さじ・小さじ・カップ・ml・cc）— タスクの指示どおり汎用エントリを
--      投入しているため、食材固有エントリが無い食品は **失敗しない**。
--      Requirement 5.3に従い、水基準の汎用値（大さじ15g・小さじ5g・カップ200g・
--      ml 1g・cc 1g）に **黙ってフォールバックする**。水と密度が異なる食品では
--      これは誤ったグラム量となり、しかもエラーにならないため検出されない。
--      例（大さじ1あたり、正しい値が判明していれば括弧内）:
--        黒砂糖    汎用15g（実際は約9g想定）→ 約+67%、エネルギー・炭水化物を過大評価
--        ラー油    汎用15g（実際は油の12g想定）→ 約+25%、脂質・エネルギーを過大評価
--        減塩しょうゆ 汎用15g（実際はしょうゆの18g想定）→ 約-17%、食塩相当量を過小評価
--      これは本マイグレーションが受け入れている **既知の制約** であり、
--      `unit_not_found` で守られてはいない。該当食品を減らすには実在の出典値を
--      見つけて食材固有エントリを追加するしかない。
--      現時点で該当する `調味料類` の食品IDは
--      `unit-conversions-seed.test.ts` の
--      「pins the 調味料類 foods that silently fall back to the generic water-basis
--        大さじ/小さじ」テストに列挙して固定してある。
--      （なお `かつおだし`(17019)・`かつお・昆布だし`(17021) のようにほぼ水と同密度の
--        だし汁については、汎用値へのフォールバックは実質的に正しい。
--        該当する全食品が誤差を持つわけではない点に注意。）
--
-- 【意図的に投入を見送った組み合わせ】
-- task 2.1が設定した152件の `(food_id, display_unit_code)` のうち、以下は信頼できる
-- 出典値を確認できなかったため投入していない。いずれも推定値を置くより
-- `unit_not_found`（Requirement 5.4）とする方が安全という判断である。
--  - `束`（にら以外の11件: ほうれんそう・こまつな・しゅんぎく・葉ねぎ・こねぎ・
--    チンゲンサイ・みずな・かぶの葉・だいこんの葉・糸みつば・モロヘイヤ）
--    「1束」の重量は出典間の食い違いが大きい（こまつな1束200g説と300g説、
--    ほうれんそう1束100g説と200g説が併存し、正味/購入時重量の別も不明）。
--    出典(B)が正味量を明示している「にら 1束 100g」のみを採用した。
--  - `缶` のうち2件（さば水煮缶・うずら卵水煮缶）のみ。
--    成分表の缶詰の成分値は備考欄に「液汁を除いたもの」と明記されており、必要なのは
--    製品の「内容総量」ではなく「固形量」である。
--    ここで単位の種類ではなく **製品カテゴリ** によって事情が分かれる点に注意:
--      * 農産物缶詰（大豆水煮・スイートコーン・トマトホール）は食品表示基準 別表第4により
--        固形量の表示が義務付けられているため、実際の製品ラベルから固形量を確認でき、
--        上記セクション4で投入済みである。
--      * 一方、魚類の水煮缶詰（さば水煮缶）は固形量の管理が困難であることを理由に
--        固形量表示が免除されており、法令上「内容総量」のみが表示される。
--        そのため固形量を確認する手段が無く、投入できない。
--        うずら卵水煮缶についても実際の製品表示で固形量を確認できなかった。
--    ※ 以前のバージョンでは「缶は一律に固形量が得られない」と記載していたが、
--      これは魚類水煮缶にのみ当てはまる話であり、農産物缶詰には当てはまらない。
--  - 菓子類・菓子パン類の`個`/`枚`/`本`（大福もち・どら焼・まんじゅう・肉まん・
--    あんパン・クリームパン・メロンパン・ドーナッツ・ケーキ類・プリン・
--    シュークリーム・キャラメル・せんべい・ビスケット・板チョコ・ホットケーキ・
--    くし団子）。いずれも市販製品ごとの重量差が大きい。
--  - パン類の`個`（ロールパン・クロワッサン・イングリッシュマフィン・ベーグル・
--    切りもち）、`パック`の一部（ミニトマト・いちご・ブルーベリー・キムチ・
--    かいわれ・めかぶ・もずく・蒸し大豆・だいずもやし）、
--    `個`の一部（にんにく・レモン全果・梅干し・プルーン乾・いちじく乾・
--    乾しいたけ・日本ぐり・ヨーグルト・アイスクリーム・固形ブイヨン・
--    がんもどき・カリフラワー・赤ピーマン）、`本`の一部（ゴーヤ・鶏手羽・
--    焼き竹輪・かに風味かまぼこ）、`枚`の一部（厚揚げ・はんぺん・
--    さつま揚げ・板こんにゃく）、`玉`の一部（そば・生うどん・
--    生中華めん・ゆで中華めん・サラダな）。
--    ※`赤ピーマン`は出典(B)が1個100g、出典(A)(C)が1個150g（購入時）と食い違い、
--      `カリフラワー`も出典(B)1個500g（正味）と出典(C)1個500g（基準不明）が
--      両立しないため、いずれも採用を見送った。

