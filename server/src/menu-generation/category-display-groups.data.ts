/**
 * 食品カテゴリ（`food_items.category`）→ 買い物リスト表示グループの静的マッピング。
 *
 * `food_items.category` は MEXT「日本食品標準成分表（八訂）増補2023年」の食品群番号とは
 * 一致しない、本アプリケーション独自の分類であり、`010_seed_food_items.sql`（task 2.1）の
 * 冒頭コメントとtasks.md「Implementation Notes」の (2.1) エントリが記録する通り、
 * 現在361件の食品カタログ全体は以下の10種類のカテゴリのみに収まる（2026-09時点で
 * 実際のマイグレーションファイルに対して確認済み。本ファイルのテストはこの前提を
 * 実際のDBに対して継続的に再検証する）:
 *   主食(36) / 肉類(28) / 魚介類(45) / 卵類(8) / 乳類(20) / 豆類(24) /
 *   野菜類(86) / 果実類(28) / 調味料類(58) / 菓子類(28)
 *
 * 要件14.4は買い物リストの各品目を次の4つの固定表示グループのいずれかに分類することを
 * 要求する（design.md #ShoppingListService の `ShoppingListItem.category` と同一の
 * リテラル文字列）: 「野菜・きのこ」「肉・魚」「乳製品・卵・豆」「調味料・その他」。
 * 要件14.5は、分類先が定義されていない食品カテゴリの品目を「調味料・その他」へ
 * フォールバックさせることを要求する。
 *
 * ## マッピング方針
 *
 * 10種類のうち6種類は表示グループへの対応が明確（グループ名に品目そのものが
 * 含まれる、または品目とグループが1対1で一致する）:
 *   - 肉類・魚介類 → 「肉・魚」
 *   - 卵類・乳類・豆類 → 「乳製品・卵・豆」（グループ名が卵/乳製品/豆を明記）
 *   - 野菜類 → 「野菜・きのこ」
 *
 * 残る4種類（主食・果実類・調味料類・菓子類）は4グループのいずれとも意味的に
 * 完全一致しないため、「週1回のまとめ買い」を行う買い物客が実際にどの売り場を
 * 探すか、という買い物リストとしての実用性の観点から個別に判断した
 * （各判断の理由は下記マッピング定義内のコメントを参照）。
 *
 * この4グループへの分類は買い物リストの表示専用の関心事であり、栄養価計算
 * （`NutritionVerificationService`等）には一切影響しない。
 *
 * ## 将来の保守者・他コンポーネントへの注意（design.md Revalidation Triggers）
 *
 * design.md はこのファイルの更新を「買い物リストのカテゴリ分類結果・外食代替提案の
 * 選定結果への影響を再確認する必要がある」変更点として明記している。`food_items`の
 * シードデータが将来更新され、ここに定義のない新しいカテゴリ文字列が追加された場合、
 * `resolveDisplayGroup` は要件14.5に従い自動的に「調味料・その他」へフォールバック
 * するため機能的には安全だが、その新カテゴリが本当に「調味料・その他」で妥当かは
 * 別途判断が必要（例えば新たに「乳製品」寄りの食品群が追加された場合など）。
 * `results-dashboard` はこのマッピングの分類結果をそのまま表示に用いるため、
 * この分類ロジック自体には関知しない。
 */

/** 買い物リストの品目が分類される4つの固定表示グループ（design.md #ShoppingListService の `ShoppingListItem.category` と同一のリテラル型）。 */
export type DisplayGroup = "野菜・きのこ" | "肉・魚" | "乳製品・卵・豆" | "調味料・その他";

/** `DisplayGroup` の全値を列挙したもの（走査・テスト用）。 */
export const ALL_DISPLAY_GROUPS: readonly DisplayGroup[] = [
  "野菜・きのこ",
  "肉・魚",
  "乳製品・卵・豆",
  "調味料・その他",
];

/**
 * `food_items.category`（現在実在する10種類）→ `DisplayGroup` の明示的マッピング。
 *
 * ここに存在しないカテゴリ文字列は `resolveDisplayGroup` が要件14.5に従い
 * 「調味料・その他」へフォールバックする（未知の将来カテゴリに対する安全側の挙動）。
 */
export const CATEGORY_DISPLAY_GROUPS: Readonly<Record<string, DisplayGroup>> = {
  // --- 明確に一致するカテゴリ ---
  肉類: "肉・魚",
  魚介類: "肉・魚",
  卵類: "乳製品・卵・豆", // グループ名が「卵」を明記
  乳類: "乳製品・卵・豆", // グループ名が「乳製品」を明記
  豆類: "乳製品・卵・豆", // グループ名が「豆」を明記
  野菜類: "野菜・きのこ",

  // --- 判断を要したカテゴリ（理由をコメントで明示） ---

  // 調味料類: 「調味料・その他」という表示グループ名そのものと文字通り一致する、
  // 唯一テキストマッチが自明なケース。
  調味料類: "調味料・その他",

  // 果実類（りんご・バナナ・柑橘類等）: 「肉・魚」「乳製品・卵・豆」のどちらとも
  // 無関係で、「調味料・その他」に押し込むのも実店舗の売り場感覚とずれる。
  // 日本のスーパーマーケットでは野菜と果物は一般に同一の「青果」コーナーに
  // 陳列され、買い物客も同じ売り場で両方を探す。「野菜・きのこ」グループが
  // 既に「きのこ」（本カタログでは`010_seed_food_items.sql`によりMEXTのきのこ類・
  // いも類・藻類が便宜上まとめられている、野菜そのものではない品目）を含めている
  // 前例があるため、同様に実際の売り場対応を優先する判断として「野菜・きのこ」に
  // 分類する。
  果実類: "野菜・きのこ",

  // 主食（米・パン・麺・小麦粉等）: 4グループのいずれとも売り場としての対応が
  // なく（野菜でも肉・魚でも乳製品・卵・豆でもない）、実店舗でも独立した
  // 「米穀・パン・麺」売り場に置かれることが多い。4グループのどれかに無理に
  // 押し込むより、要件14.5が想定する「分類先が定義されていない」ケースの
  // フォールバック先である「調味料・その他」（＝「その他」の性質を持つ受け皿）
  // に分類するのが最も誠実な判断と考えられる。
  主食: "調味料・その他",

  // 菓子類（洋菓子・和菓子・スナック・種実類由来のナッツ等）: 同様に4グループの
  // いずれとも売り場としての対応がなく、実店舗でも独立した菓子売り場に置かれる。
  // 主食と同じ理由で「調味料・その他」に分類する。
  菓子類: "調味料・その他",
};

/**
 * 食品カテゴリ文字列を買い物リスト表示グループへ解決する（要件14.4）。
 *
 * `CATEGORY_DISPLAY_GROUPS` に定義のないカテゴリ（将来のシードデータ変更で
 * 追加された未知のカテゴリ等）は「調味料・その他」へフォールバックする（要件14.5）。
 *
 * `ShoppingListService`（task 13.1）は、`FoodCompositionRepository`から解決した
 * 各品目の`category`をそのままこの関数に渡し、返り値を`ShoppingListItem.category`
 * として使用することを想定する。
 */
export function resolveDisplayGroup(category: string): DisplayGroup {
  return CATEGORY_DISPLAY_GROUPS[category] ?? "調味料・その他";
}
